create table if not exists public.ravine_hero_settings (
  id integer primary key check (id = 1),
  use_curated_media boolean not null default false,
  updated_by uuid references auth.users(id) on delete set null,
  updated_at timestamptz not null default now()
);

insert into public.ravine_hero_settings (id, use_curated_media)
values (1, false)
on conflict (id) do nothing;

create table if not exists public.ravine_hero_media_items (
  id bigint generated by default as identity primary key,
  media_type text not null check (media_type in ('video', 'image')),
  title text not null,
  media_url text not null,
  thumbnail_url text,
  video_id bigint references public.videos(id) on delete cascade,
  sort_order integer not null default 0,
  is_active boolean not null default true,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint ravine_hero_media_type_source_check check (
    (media_type = 'video' and video_id is not null) or
    (media_type = 'image' and video_id is null)
  )
);

create unique index if not exists ravine_hero_media_video_unique
  on public.ravine_hero_media_items (video_id)
  where media_type = 'video' and video_id is not null;

create index if not exists ravine_hero_media_active_order_idx
  on public.ravine_hero_media_items (is_active, sort_order, id);

alter table public.ravine_hero_settings enable row level security;
alter table public.ravine_hero_media_items enable row level security;

revoke all on table public.ravine_hero_settings from anon, authenticated;
revoke all on table public.ravine_hero_media_items from anon, authenticated;

grant select on table public.ravine_hero_settings to anon, authenticated;
grant update on table public.ravine_hero_settings to authenticated;

grant select on table public.ravine_hero_media_items to anon, authenticated;
grant insert, update, delete on table public.ravine_hero_media_items to authenticated;
grant usage, select on sequence public.ravine_hero_media_items_id_seq to authenticated;

drop policy if exists "Hero settings are publicly readable" on public.ravine_hero_settings;
create policy "Hero settings are publicly readable"
  on public.ravine_hero_settings
  for select
  to anon, authenticated
  using (true);

drop policy if exists "RAVINE admins update hero settings" on public.ravine_hero_settings;
create policy "RAVINE admins update hero settings"
  on public.ravine_hero_settings
  for update
  to authenticated
  using ((select public.is_ravine_admin()))
  with check ((select public.is_ravine_admin()));

drop policy if exists "Only active hero media is public" on public.ravine_hero_media_items;
create policy "Only active hero media is public"
  on public.ravine_hero_media_items
  for select
  to anon, authenticated
  using (is_active = true);

drop policy if exists "RAVINE admins can inspect all hero media" on public.ravine_hero_media_items;
