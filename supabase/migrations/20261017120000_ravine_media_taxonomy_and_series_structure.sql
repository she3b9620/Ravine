-- RAVINE seven-format media taxonomy and structured series publishing.
-- Staged in the feature branch. Do not apply to the connected production database without approval.

create table if not exists public.ravine_series_titles (
  id bigint generated by default as identity primary key,
  creator_id bigint not null references public.creators(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null check (length(btrim(title)) > 0),
  description text,
  poster_url text,
  published boolean not null default false,
  visibility text not null default 'public'
    check (visibility in ('public','followers','unlisted','private','custom')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (creator_id, title)
);

create index if not exists ravine_series_titles_creator_idx on public.ravine_series_titles(creator_id, created_at desc);
create index if not exists ravine_series_titles_public_idx on public.ravine_series_titles(published, visibility, created_at desc);

alter table public.videos
  add column if not exists series_id bigint references public.ravine_series_titles(id) on delete set null,
  add column if not exists season_number integer,
  add column if not exists episode_number integer;

create index if not exists videos_series_episode_order_idx
  on public.videos(series_id, season_number, episode_number) where series_id is not null;
create unique index if not exists videos_series_episode_unique_idx
  on public.videos(series_id, season_number, episode_number)
  where series_id is not null and season_number is not null and episode_number is not null;

alter table public.ravine_series_titles enable row level security;

drop policy if exists ravine_series_titles_select_owner_or_public on public.ravine_series_titles;
create policy ravine_series_titles_select_owner_or_public on public.ravine_series_titles
for select to anon, authenticated
using ((auth.uid() is not null and user_id = auth.uid()) or (published = true and visibility = 'public'));

drop policy if exists ravine_series_titles_owner_insert on public.ravine_series_titles;
create policy ravine_series_titles_owner_insert on public.ravine_series_titles
for insert to authenticated
with check (user_id = auth.uid() and exists (select 1 from public.creators c where c.id = creator_id and c.user_id = auth.uid()));

drop policy if exists ravine_series_titles_owner_update on public.ravine_series_titles;
create policy ravine_series_titles_owner_update on public.ravine_series_titles
for update to authenticated
using (user_id = auth.uid() and exists (select 1 from public.creators c where c.id = creator_id and c.user_id = auth.uid()))
with check (user_id = auth.uid() and exists (select 1 from public.creators c where c.id = creator_id and c.user_id = auth.uid()));

drop policy if exists ravine_series_titles_owner_delete on public.ravine_series_titles;
create policy ravine_series_titles_owner_delete on public.ravine_series_titles
for delete to authenticated
using (user_id = auth.uid() and exists (select 1 from public.creators c where c.id = creator_id and c.user_id = auth.uid()));

grant select on public.ravine_series_titles to anon, authenticated;
grant insert, update, delete on public.ravine_series_titles to authenticated;
grant usage, select on sequence public.ravine_series_titles_id_seq to authenticated;

alter table public.videos drop constraint if exists videos_content_type_check;
alter table public.videos add constraint videos_content_type_check
check (content_type = any (array['short','video','podcast','live','film','documentary','series','short_film']));

create or replace function public.ravine_enforce_upload_policy()
returns trigger language plpgsql security definer set search_path = public
as $$
declare
  actor uuid := auth.uid();
  founder boolean := false;
  unlimited boolean := false;
  current_used integer := 0;
  current_limit integer := 0;
begin
  if actor is null then raise exception 'RAVINE_AUTH_REQUIRED' using errcode = '42501'; end if;
  if new.user_id is null then new.user_id := actor; end if;
  if new.user_id <> actor and not is_ravine_admin() then
    raise exception 'RAVINE_UPLOAD_OWNER_MISMATCH' using errcode = '42501';
  end if;

  founder := exists (select 1 from public.ravine_founders f where f.user_id = actor and f.is_active = true);
  unlimited := founder or exists (select 1 from public.creators c where c.id = new.creator_id and c.user_id = actor);

  if new.content_type not in ('short','video','podcast','live','film','short_film','documentary','series') then
    raise exception 'RAVINE_INVALID_CONTENT_TYPE' using errcode = '22023';
  end if;

  if new.content_type = 'series' then
    if new.series_id is null or coalesce(new.season_number, 0) < 1 or coalesce(new.episode_number, 0) < 1 then
      raise exception 'RAVINE_SERIES_EPISODE_METADATA_REQUIRED' using errcode = '22023';
    end if;
    if not exists (select 1 from public.ravine_series_titles s where s.id = new.series_id and s.creator_id = new.creator_id and s.user_id = actor) then
      raise exception 'RAVINE_SERIES_OWNER_MISMATCH' using errcode = '42501';
    end if;
  end if;

  if unlimited or new.content_type = 'live' then return new; end if;

  insert into public.upload_limits (user_id) values (actor) on conflict (user_id) do nothing;
  update public.upload_limits
  set shorts_used = case when reset_date <= now() then 0 else shorts_used end,
      videos_used = case when reset_date <= now() then 0 else videos_used end,
      podcasts_used = case when reset_date <= now() then 0 else podcasts_used end,
      reset_date = case when reset_date <= now() then date_trunc('month', now()) + interval '1 month' else reset_date end
  where user_id = actor;

  if new.content_type = 'short' then
    select shorts_used, shorts_monthly into current_used, current_limit from public.upload_limits where user_id = actor for update;
    if current_used >= current_limit then raise exception 'RAVINE_SHORT_QUOTA_EXCEEDED' using errcode = 'check_violation'; end if;
    update public.upload_limits set shorts_used = shorts_used + 1 where user_id = actor;
  elsif new.content_type in ('video','film','short_film','documentary','series') then
    select videos_used, videos_monthly into current_used, current_limit from public.upload_limits where user_id = actor for update;
    if current_used >= current_limit then raise exception 'RAVINE_VIDEO_QUOTA_EXCEEDED' using errcode = 'check_violation'; end if;
    update public.upload_limits set videos_used = videos_used + 1 where user_id = actor;
  elsif new.content_type = 'podcast' then
    select podcasts_used, podcasts_monthly into current_used, current_limit from public.upload_limits where user_id = actor for update;
    if current_used >= current_limit then raise exception 'RAVINE_PODCAST_QUOTA_EXCEEDED' using errcode = 'check_violation'; end if;
    update public.upload_limits set podcasts_used = podcasts_used + 1 where user_id = actor;
  end if;
  return new;
end;
$$;

revoke all on function public.ravine_enforce_upload_policy() from public;
drop trigger if exists ravine_enforce_upload_policy_trigger on public.videos;
create trigger ravine_enforce_upload_policy_trigger before insert on public.videos for each row execute function public.ravine_enforce_upload_policy();

comment on table public.ravine_series_titles is 'Series-level metadata. Individual episodes remain videos linked through series_id and season/episode numbering.';
comment on function public.ravine_enforce_upload_policy() is 'Restricts uploads to signed-in owners, validates series parent ownership, and enforces existing monthly format quotas.';
