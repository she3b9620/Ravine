-- Minimal Supabase-compatible prerequisites for offline migration smoke tests only.
-- This database is ephemeral GitHub Actions PostgreSQL, never the connected Supabase project.
CREATE ROLE anon NOLOGIN;
CREATE ROLE authenticated NOLOGIN;
CREATE ROLE service_role NOLOGIN BYPASSRLS;

CREATE SCHEMA auth;
CREATE TABLE auth.users (
  id uuid PRIMARY KEY,
  email text
);
CREATE OR REPLACE FUNCTION auth.uid()
RETURNS uuid
LANGUAGE sql
STABLE
AS $$
  SELECT nullif(current_setting('request.jwt.claim.sub', true), '')::uuid
$$;

CREATE TABLE public.creators (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  name text,
  username text,
  avatar_url text,
  bio text,
  specialty text
);

CREATE TABLE public.videos (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  creator_id bigint REFERENCES public.creators(id) ON DELETE SET NULL,
  user_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  content_type text,
  published boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE OR REPLACE FUNCTION public.is_ravine_admin()
RETURNS boolean
LANGUAGE sql
STABLE
AS $$
  SELECT false
$$;
