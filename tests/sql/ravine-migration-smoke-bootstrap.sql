-- Minimal Supabase-compatible prerequisites for offline migration smoke tests only.
-- This database is ephemeral GitHub Actions PostgreSQL, never the connected Supabase project.
CREATE ROLE anon NOLOGIN;
CREATE ROLE authenticated NOLOGIN;
CREATE ROLE service_role NOLOGIN BYPASSRLS;

CREATE SCHEMA auth;
CREATE TABLE auth.users (
  id uuid PRIMARY KEY,
  email text
);
CREATE OR REPLACE FUNCTION auth.uid()
RETURNS uuid
LANGUAGE sql
STABLE
AS $$
  SELECT nullif(current_setting('request.jwt.claim.sub', true), '')::uuid
$$;

CREATE TABLE public.creators (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  name text,
  username text,
  avatar_url text,
  bio text,
  specialty text
);

CREATE TABLE public.communities (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  name text
);

CREATE TABLE public.work_media_assets (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
);

CREATE TABLE public.videos (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  creator_id bigint REFERENCES public.creators(id) ON DELETE SET NULL,
  user_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  title text NOT NULL DEFAULT 'Smoke test video',
  description text,
  video_url text,
  thumbnail_url text,
  duration integer,
  views bigint DEFAULT 0,
  likes bigint DEFAULT 0,
  content_type text,
  published boolean NOT NULL DEFAULT false,
  visibility text NOT NULL DEFAULT 'public',
  discovery_enabled boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE OR REPLACE FUNCTION public.is_ravine_admin()
RETURNS boolean
LANGUAGE sql
STABLE
AS $$
  SELECT false
$$;
